//! Folder names, and the generated `chat.md` view.

use std::fmt::Write as _;

use super::state::{ChatState, CompRec, Msg};
use crate::model::{Millis, Role};

/// Longest slug part of a folder name, in bytes (ASCII).
const MAX_SLUG: usize = 40;

/// `title` as a lowercase ASCII slug: letters and digits kept, runs of anything else become
/// one `-`. Non-ASCII titles (or empty ones) give `chat`.
pub(crate) fn slug(title: &str) -> String {
    let mut out = String::new();
    for c in title.chars() {
        if c.is_ascii_alphanumeric() {
            if out.len() >= MAX_SLUG {
                break;
            }
            out.push(c.to_ascii_lowercase());
        } else if !out.is_empty() && !out.ends_with('-') {
            out.push('-');
        }
    }
    let out = out.trim_matches('-');
    if out.is_empty() { "chat".to_owned() } else { out.to_owned() }
}

/// Six hex digits derived from the chat id (FNV-1a), so names differ even for chats with the
/// same title and day. The full id lives inside the folder; this is only for humans.
pub(crate) fn short_id(id: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in id.bytes() {
        h ^= u64::from(b);
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{:06x}", h >> 40)
}

fn utc(ms: Millis, fmt: &str) -> String {
    chrono::DateTime::from_timestamp_millis(ms).map(|t| t.format(fmt).to_string()).unwrap_or_else(|| ms.to_string())
}

/// `<YYYY-MM-DD>-<slug>-<shortid>` (UTC date of creation).
pub(crate) fn folder_name(created_at: Millis, title: &str, id: &str) -> String {
    format!("{}-{}-{}", utc(created_at, "%Y-%m-%d"), slug(title), short_id(id))
}

/// A YAML double-quoted scalar (JSON string syntax is valid YAML).
fn yaml_str(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| "\"\"".to_owned())
}

fn who(role: Role) -> &'static str {
    match role {
        Role::User => "You",
        Role::Assistant => "byob",
        Role::System => "System",
        Role::Tool => "Tool",
    }
}

fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn render_message(out: &mut String, msg: &Msg) {
    let mut flags = String::new();
    if !msg.done {
        flags.push_str(" · _unfinished_");
    }
    if msg.undone {
        flags.push_str(" · _changes undone_");
    }
    let _ = writeln!(out, "## {} · {}{flags}\n", who(msg.role), utc(msg.created_at, "%Y-%m-%d %H:%M UTC"));
    if !msg.reasoning.trim().is_empty() {
        let _ = writeln!(out, "<details><summary>Thinking</summary>\n\n{}\n\n</details>\n", msg.reasoning.trim_end());
    }
    if !msg.steps.is_empty() {
        let mut steps: Vec<_> = msg.steps.iter().collect();
        steps.sort_by_key(|s| s.seq);
        for s in steps {
            let (mark, note) = match &s.result {
                None => ("…", " (running or interrupted)"),
                Some(r) if r.failed => ("✗", " (failed)"),
                Some(_) => ("✓", ""),
            };
            let _ = writeln!(out, "- {mark} `{}` {}{note}", one_line(&s.tool), one_line(&s.title));
        }
        out.push('\n');
    }
    if !msg.content.trim().is_empty() {
        let _ = writeln!(out, "{}\n", msg.content.trim_end());
    }
    if let Some(e) = &msg.error {
        let _ = writeln!(out, "> **Error:** {}\n", one_line(e));
    }
}

fn render_compaction(out: &mut String, c: &CompRec) {
    let how = if c.manual { "asked for" } else { "automatic" };
    let focus = c.focus.as_deref().map(|f| format!(", focus: {}", one_line(f))).unwrap_or_default();
    let _ = writeln!(
        out,
        "_— context compacted —_ ({how}{focus}, ~{} → ~{} tokens, {})\n",
        c.tokens_before,
        c.tokens_after,
        utc(c.created_at, "%Y-%m-%d %H:%M UTC")
    );
    let _ = writeln!(out, "<details><summary>Summary the model continues from</summary>\n\n{}\n\n</details>\n", c.summary.trim_end());
}

/// The human-readable view: YAML frontmatter, then the transcript. Generated from the
/// events, never read back.
pub(crate) fn chat_md(state: &ChatState) -> String {
    let c = &state.chat;
    let mut out = String::new();
    out.push_str("---\n");
    let _ = writeln!(out, "title: {}", yaml_str(&c.title));
    let _ = writeln!(out, "id: {}", yaml_str(&c.id));
    let _ = writeln!(out, "created: {}", utc(c.created_at, "%Y-%m-%dT%H:%M:%SZ"));
    let _ = writeln!(out, "updated: {}", utc(c.updated_at, "%Y-%m-%dT%H:%M:%SZ"));
    let _ = writeln!(out, "workspace: {}", yaml_str(&c.workspace.to_string_lossy()));
    if c.pinned_at.is_some() {
        out.push_str("pinned: true\n");
    }
    out.push_str("---\n\n");
    out.push_str("<!-- Generated by byob from events.jsonl; edits here are overwritten. -->\n\n");
    let _ = writeln!(out, "# {}\n", one_line(&c.title));
    // Each compaction note goes right after the last message it covers.
    let mut sorted: Vec<&CompRec> = state.compactions.iter().collect();
    sorted.sort_by_key(|c| (c.through, c.n));
    let mut comps = sorted.into_iter().peekable();
    for (n, msg) in &state.messages {
        while let Some(c) = comps.next_if(|c| c.through < *n) {
            render_compaction(&mut out, c);
        }
        render_message(&mut out, msg);
    }
    for c in comps {
        render_compaction(&mut out, c);
    }
    out
}
